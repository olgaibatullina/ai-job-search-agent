"""LLM-based preprocessing of raw job descriptions."""

import json

from langchain_ollama import ChatOllama
from config import paths


MODEL_NAME = "qwen3-h7"

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------
# The LLM is used only to compress the raw job description into a
# retrieval-oriented representation.
#
# The original job description remains the source of truth. The LLM should
# preserve information that can affect semantic job matching while removing
# non-informative content such as company marketing, benefits, and boilerplate.
#
# The job title is intentionally NOT generated by the LLM. It is taken
# directly from the original structured job data and prepended to the
# generated retrieval description. This preserves the exact role title as
# an important retrieval signal.
PROMPT = """
    Rewrite the job description into a concise, retrieval-optimized representation.

    Preserve the complete set of information that is relevant for semantic job matching. The rewritten description should retain:
        - core responsibilities and types of work performed
        - required skills, technologies, tools, frameworks, and methodologies
        - preferred and nice-to-have qualifications
        - years of experience and other quantitative requirements
        - education and certification requirements
        - domain and industry experience
        - location, workplace type, employment type, and work authorization requirements
        - other candidate eligibility criteria that may affect job matching
        - important technical terminology and domain-specific keywords
    
    Preserve the distinction between required, preferred, and nice-to-have qualifications.

    Preserve specific technologies and tools by name. Preserve the original seniority and role level exactly as stated.

    Use the original job description as the source of truth. Represent only information supported by the original description.

    Remove corporate marketing language, benefits, generic EEO statements, application instructions, legal boilerplate, recruiting-process information, and unrelated company background.

    Organize the result around:
        - Core responsibilities
        - Required qualifications
        - Preferred qualifications
        - Technical skills and tools
        - Domain / industry
        - Important constraints and eligibility requirements
    The result should be substantially more concise than the original while preserving all information that can affect semantic job matching.

    Return ONLY the rewritten description as plain text.
    Do not add headings or commentary.

    JOB DESCRIPTION:
"""


# ---------------------------------------------------------------------------
# LLM
# ---------------------------------------------------------------------------
# Use a local Qwen model so preprocessing can be reproduced without an
# external API. Temperature=0 reduces variation between preprocessing runs.
def create_llm() -> ChatOllama:
    return ChatOllama(
        model=MODEL_NAME,
        temperature=0,
    )


# ---------------------------------------------------------------------------
# Single job preprocessing
# ---------------------------------------------------------------------------
# Transform one job by generating only the retrieval representation.
#
# All original job fields are preserved unchanged. The only newly generated
# field is `retrieval_description`, which is later used as the input for
# embedding and vector retrieval.
def preprocess_job(
    job: dict,
    llm: ChatOllama,
) -> dict:

    description = job.get("posting", {}).get("description")

    if not description:
        raise ValueError(
            f"Job {job.get('job_id')} has no description."
        )

    print(
        f"------------- Calling {MODEL_NAME} for {job['job_id']} "
        f"(description chars: {len(description)}, "
        f"prompt chars: {len(PROMPT)})",
        flush=True,
    )

    # Limit the input length to avoid excessively large LLM requests.
    # This is a preprocessing/infrastructure constraint, not a modification
    # of the stored raw description.
    response = llm.invoke(
        PROMPT + description[:6000]
    )

    # The title comes directly from the original dataset rather than from
    # the LLM. This guarantees that the exact job title is retained as an
    # explicit retrieval signal.
    retrieval_description = (
        f"{job['job']['title']}\n\n"
        + response.content.strip()
    )

    print(
        f"Qwen response received for {job['job_id']}",
        flush=True,
    )

    # Preserve the complete original job record and add the generated
    # retrieval representation. The original description is therefore still
    # available for evaluation and later comparison with the compressed text.
    return {
        **job,
        "retrieval_description": retrieval_description,
    }


# ---------------------------------------------------------------------------
# Input dataset
# ---------------------------------------------------------------------------
# Load the current job dataset that will be used as input for LLM preprocessing.
# The original job records are preserved unchanged; preprocessing only adds
# the generated `retrieval_description` field.
def load_input_jobs() -> list[dict]:
    with paths.PROCESSED_JOBS.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


# ---------------------------------------------------------------------------
# Full dataset preprocessing
# ---------------------------------------------------------------------------
# Run LLM preprocessing for every job in the dataset.
#
# Jobs are processed sequentially to keep local LLM resource usage predictable
# and to make progress/errors easy to track during preprocessing.
def preprocess_jobs(
    jobs: list[dict],
    llm: ChatOllama,
) -> list[dict]:
    """Process the complete job dataset."""

    processed_jobs = []

    for index, job in enumerate(jobs, start=1):
        print(
            f"[{index}/{len(jobs)}] "
            f"Processing {job['job_id']}..."
        )

        processed_job = preprocess_job(
            job=job,
            llm=llm,
        )

        processed_jobs.append(processed_job)

    return processed_jobs


# ---------------------------------------------------------------------------
# Save processed dataset
# ---------------------------------------------------------------------------
# Save the original job data together with the generated retrieval
# representation. Keeping both allows the original description and the
# LLM-generated representation to be compared during retrieval evaluation.
def save_processed_jobs(
    jobs: list[dict],
    output_path,
) -> None:
    """Save processed jobs as JSON."""

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with output_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            jobs,
            file,
            ensure_ascii=False,
            indent=2,
        )


# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------
# Pipeline:
#   1. Load the input job dataset.
#   2. Generate a compact retrieval description for each job using Qwen.
#   3. Preserve the original job data and add the retrieval representation.
#   4. Save the resulting dataset for embedding and retrieval evaluation.
def main() -> None:
    """Run the preprocessing pipeline."""

    jobs = load_input_jobs()

    print(f"Loaded {len(jobs)} jobs.")

    llm = create_llm()

    processed_jobs = preprocess_jobs(
        jobs=jobs,
        llm=llm,
    )

    output_path = paths.PROCESSED_JOBS.parent / "processed_jobs.json"

    save_processed_jobs(
        jobs=processed_jobs,
        output_path=output_path,
    )

    print()
    print(f"Processed {len(processed_jobs)} jobs.")
    print(f"Saved to: {output_path}")


if __name__ == "__main__":
    main()